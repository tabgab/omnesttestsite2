<b>"Modeling and Tools for Network Simulation"</b> (Klaus Wehrle, Mesut
G&uuml;nes, James Gross [Editors], Springer, 2010) is a book that focuses on
tools, modeling principles and state-of-the art models for discrete-event
based network simulations. The focus of the "tools" part is on two distinct
simulations engines: OMNeT++ and ns-3, where the OMNeT++ chapter presents a
high-level overview and rationale of the concepts, techniques and tools
present in that simulation environment. The book also deals with issues
like parallelization, software integration and hardware simulations. In the
"modeling" part of the book, the wireless section covers all essential
modeling principles for dealing with physical layer, link layer and
wireless channel behavior, and presents detailed models for IEEE 802.11,
IEEE 802.16 and other systems. Further chapters cover classical modeling
approaches for higher layers (network layer, transport layer and
application layer) and modeling approaches for peer-to-peer networks and
topologies of networks.
</p>

