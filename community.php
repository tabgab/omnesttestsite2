<p>The OMNeT++ Workshop (<a href="http://omnet-workshop.org" target="_top">omnet-workshop.org</a>)
is an annual international event which serves as a meeting place for OMNeT++ (and OMNEST) users,
and as an opportunity to present their research results and simulation models. Traditionally,
the workshop is a joint event of the ICST SimuTools conference
(<a href="http://simutools.org" target="_top">simutools.org</a>), and accepted papers
are included in the ACM Digital Library.</p>

<p>In recent years, we have been able to welcome participants not only from universities
from many countries, but also from major companies and renowned research institutes
such as the IBM Zurich Research Laboratory, Alcatel-Lucent France, Thales France,
Fraunhofer (Germany) and CSEM (Switzerland), among others.</p>

