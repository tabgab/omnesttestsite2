<div id="header"><h1>MiXiM -- Detailed PHY and MAC Layer Simulations</h1></div>

<p>Home page: <a href="http://mixim.sourceforge.net" target="_blank" class="kiemeles">mixim.sourceforge.net</a></p>

<div class="pic right" style="width: 295px">
<img src="images/misc/mixim-signal.png" alt="MiXiM Signal"/>
<div>MiXiM can represent the power of a transmitted radio signal (air frame)
over time, frequency and/or space with a multi-dimensional mapping (figure from the paper).</div>
</div>

<p>MiXiM is an open-source OMNeT++/OMNEST modeling framework created for mobile
and fixed wireless networks (wireless sensor networks, body area networks,
ad-hoc networks, vehicular networks, etc.). MiXiM concentrates on accurate
radio channel modeling and the physical and medium access layers: it offers
detailed models of radio wave propagation, interference estimation, radio
transceiver power consumption and wireless MAC protocols like Zigbee.
</p>

<p>MiXiM may also be used together with the INET Framework to utilize its
the higher-layer protocol implementations.
</p>

<p>Documentation (tutorials, examples, etc.) are available on the MiXiM
project web site. In addition, the following papers describe the
principles, architecture and implementation of MiXiM:
</p>

